export const exCompressionCode = [
  '// ===== aipack-compression：五级上下文压缩 =====',
  '// 注意：compression 是可选的，默认关闭。动态 import 方式避免硬依赖。',
  'import {',
  '  createRuntime,',
  '  createRequest,',
  '  getBuiltinModel, adaptAiModel, createStreamFnFromAi,',
  '  createDefaultTransformers,',
  '} from "@aipack-ai/agent";',
  '',
  'async function main() {',
  '  const ai = getBuiltinModel("deepseek", "deepseek-chat");',
  '  const model = adaptAiModel(ai);',
  '',
  '  // 动态加载 compression（推荐）',
  '  const { createCompressionTransformer, loadCompressionConfig } = await import("@aipack-ai/compression");',
  '',
  '  // 基于默认配置 + 覆盖项构造压缩配置（未覆盖项使用默认值，也支持 AIPACK_L1_* 等环境变量覆盖）',
  '  const config = loadCompressionConfig({',
  '    enabled: true,',
  '    // L1 工具输出裁剪：保留结构，只保留前 N 行+后 N 行（超大工具输出）',
  '    l1: { enabled: true, toolResultMaxLines: 50, toolResultHeadLines: 10, toolResultTailLines: 10 },',
  '    // L2 消息摘要：上下文占用超过 threshold（0.75 = 75% 窗口）时，用 fork 模型滚动摘要旧消息',
  '    l2: { enabled: true, threshold: 0.75, targetRatio: 0.60, minResourcesToCompress: 4, protectedRecentCount: 6 },',
  '    // L3 任务状态提取：从对话中提取结构化任务状态（进行中 / 待办 / 阻塞）',
  '    l3: { enabled: true, threshold: 0.85, targetRatio: 0.40 },',
  '    // L4 会话检查点：接近满窗口时把完整会话持久化到 SessionStorage，缩减为最小工作集',
  '    l4: { enabled: true, threshold: 0.92, targetRatio: 0.25, checkpointStorage: "file", minWorkingSet: 2, failOnPersistError: true },',
  '    // L5 新会话交接：超过阈值时启动新会话并生成交接文档',
  '    l5: { enabled: true, threshold: 0.95 },',
  '    // 防止过度压缩：压缩轮次 / 冷却回合限制',
  '    safety: { maxAttempts: 5, cooldownTurns: 5 },',
  '  });',
  '',
  '  const runtime = createRuntime({',
  '    model,',
  '    streamFn: createStreamFnFromAi(ai),',
  '    systemPrompt: "你是一名架构师，正在协助设计大型系统。",',
  '    transformers: [',
  '      ...createDefaultTransformers(),',
  '      // 注入压缩转换器',
  '      createCompressionTransformer({',
  '        config,',
  '        model,',
  '        streamFn: createStreamFnFromAi(ai),',
  '        contextWindow: ai.contextWindow,',
  '      }),',
  '    ],',
  '  });',
  '',
  '  // 之后正常使用 run() / stream()；压缩逻辑对调用方透明',
  '  await runtime.run(createRequest("开始设计：做一个电商系统的订单模块"));',
  '  await runtime.close();',
  '}',
].join('\n');

