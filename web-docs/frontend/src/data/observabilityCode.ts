  '// 工具成功率        onToolCall.status       ok / (ok + error)；blocked/skipped 不计入',
  '// 上下文压缩        onCompaction            次数、mode 分布（summary/truncate 比）、tokensBefore/After 压缩率',
  '// 首 token 延迟     onRunEnd.ttftMs         流式体验关键指标',
