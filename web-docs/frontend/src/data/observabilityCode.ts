export const obsTelemetryCode = [
  'import { createRuntime, createRequest } from "@aipack/agent";',
  '',
  '// Telemetry：面向生产观测的轻量埋点接口（全可选，失败不阻断主流程）',
  'const runtime = createRuntime({',
  '  model: model,',
  '  telemetry: {',
  '    // 1. run 入队（配合 onRunEnd 求排队时长 queuedMs）',
  '    onRunStart(info) {',
  '      log("run 入队", info.traceId, info.sessionKey);',
  '    },',
  '',
  '    // 2. run 完成（成功或失败均触发；流式 stream() 同样触发）',
  '    onRunEnd(info) {',
  '      log({',
  '        traceId: info.traceId,',
  '        success: info.success,',
  '        errorClass: info.errorClass, // rate-limit / timeout / terminated / validation ...',
  '        turns: info.turnCount, // step 长度',
  '        durationMs: info.durationMs,',
  '        queuedMs: info.queuedMs, // 会话串行排队时长',
  '        tokens: info.tokens,',
  '        costUsd: info.costUsd, // 已按 model.cost 计算',
  '        ttftMs: info.ttftMs, // 流式首 token 延迟',
  '      });',
  '    },',
  '',
  '    // 3. 单次模型调用（run 与 stream 两路径统一埋点）',
  '    onModelCall(info) {',
  '      log({',
  '        traceId: info.traceId,',
  '        modelId: info.modelId,',
  '        attempts: info.attempts, // 含重试：1 = 无重试',
  '        inputTokens: info.inputTokens,',
  '        outputTokens: info.outputTokens,',
  '        durationMs: info.durationMs,',
  '        stream: info.stream,',
  '        errorClass: info.errorClass,',
  '        costUsd: info.costUsd,',
  '      });',
  '    },',
  '',
  '    // 4. 单次工具执行',
  '    onToolCall(info) {',
  '      if (!info.success) {',
  '        log.warn("工具失败", info.toolName, info.status, info.errorClass, info.traceId);',
  '      }',
  '    },',
  '',
  '    // 5. provider 内部退避重试（429/5xx 等可重试错误）',
  '    onRetry(info) {',
  '      log.warn("模型重试", info.modelId, `第 ${info.attempt} 次`, info.status, `${info.delayMs}ms`);',
  '    },',
  '',
  '    // 6. 工具调用被权限策略拒绝',
  '    onPermissionDenied(info) {',
  '      log.warn("权限拒绝", info.toolName, info.reason, info.traceId);',
  '    },',
  '  },',
  '});',
  '',
  '// 每个事件的 traceId 相同 → 一次 run 的完整链路可回放',
  'const result = await runtime.run(createRequest("帮我查询今天的天气"));',
  'console.log(result.metadata.traceId); // 与 telemetry 事件中的 traceId 一致',
].join('\n');

