export const extCustomTransformerCode = [
  'import {',
  '  BaseTransformer,',
  '  type ContextResource,',
  '  type TransformContext,',
  '  resourcesToMessages,',
  '  messagesToResources,',
  '  createRequest,',
  '  createRuntime,',
  '  createDefaultTransformers,',
  '} from "@aipack-ai/agent";',
  '',
  '/**',
  ' * 自定义 Transformer：',
  ' * - 在每次模型调用前执行（按数组顺序串行，上一个的输出是下一个的输入）',
  ' * - 继承 BaseTransformer，重写 run(resources, context)',
  ' * - 典型用途：上下文裁剪、摘要、记忆注入、前缀注入、敏感词过滤等',
  ' */',
  'class MemoryInjectTransformer extends BaseTransformer {',
  '  readonly name = "memory-inject";',
  '',
  '  protected async run(resources: ContextResource[], _context: TransformContext) {',
  '    const messages = resourcesToMessages(resources);',
  '',
  '    // 只处理最后一条 user 消息（未处理过的）',
  '    const lastIdx = [...messages].reverse().findIndex(m => m.role === "user");',
  '    if (lastIdx < 0) return messagesToResources(messages);',
  '    const idx = messages.length - 1 - lastIdx;',
  '    const userMsg = messages[idx] as any;',
  '',
  '    // sentinel：已经注入过的就跳过（防累积）',
  '    const sentinel = "<<<MY_CONTEXT_BLOCK>>>";',
  '    const raw = typeof userMsg.content === "string" ? userMsg.content : "";',
  '    if (raw.includes(sentinel)) return messagesToResources(messages);',
  '',
  '    // 从 DB / 向量库 / 文件读取相关上下文',
  '    const memory = await loadRelevantMemory(raw);',
  '    if (!memory) return messagesToResources(messages);',
  '',
  '    const injected = [',
  '      sentinel,',
  '      "[相关参考资料]",',
  '      ...memory.map(m => "- " + m),',
  '      sentinel.replace(">>>", "/>>>"),',
  '      "",',
  '      raw,',
  '    ].join("\\n");',
  '',
  '    const nextMessages = [...messages];',
  '    nextMessages[idx] = { ...userMsg, content: injected };',
  '    return messagesToResources(nextMessages);',
  '  }',
  '}',
  '',
  'async function loadRelevantMemory(query: string) {',
  '  // 演示：实际中可接 BM25 / 向量检索',
  '  if (query.includes("支付")) {',
  '    return ["订单支付超时时间为 30 分钟", "支持微信、支付宝、Apple Pay"];',
  '  }',
  '  return null;',
  '}',
  '',
  '// ==== 组合使用：自定义 + 内置（推荐，内置工具配对等是必要的）====',
  'const runtime = createRuntime({',
  '  // ... model/streamFn',
  '  transformers: [',
  '    ...createDefaultTransformers(), // 内置：工具配对、系统消息清理、条数/Token 截断',
  '    new MemoryInjectTransformer(),  // 自定义：记忆注入',
  '  ],',
  '});',
].join('\n');

export const extToolHooksCode = [
  'import {',
  '  createToolHookExtension,',
  '  createRuntime,',
  '  getBuiltinModel,',
  '  adaptAiModel,',
  '  createStreamFnFromAi,',
  '} from "@aipack-ai/agent";',
  '',
  '/**',
  ' * 工具调用钩子：两个决策点',
  ' *   beforeToolCall：参数校验后、execute 前',
  ' *     返回：{ block?, terminate?, reason?, args? }',
  ' *   afterToolCall ：execute 后、事件发出前',
  ' *     返回：{ terminate?, result?, details? }',
  ' * ',
  ' * 多个扩展都可以注册钩子。AsyncSeriesWaterfall 串行执行，',
  ' * 前置 block/terminate 后，后续 beforeToolCall 会 early-return。',
  ' */',
  'const guard = createToolHookExtension({',
  '  name: "prod-safety-guard",',
  '',
  '  beforeToolCall: async (ctx) => {',
  '    // ctx 字段：',
  '    //   toolCall / tool / args / sessionKey / request / shared / signal',
  '    const { tool, args, sessionKey } = ctx;',
  '',
  '    // 1) 危险命令拦截',
  '    if (tool.name === "run_command") {',
  '      const cmd = String(args ?? "");',
  '      if (/\\brm\\s+-rf\\b|drop\\s+table/i.test(cmd)) {',
  '        return {',
  '          block: true,',
  '          reason: "[安全拦截] 该命令被管理员策略禁止",',
  '          // terminate: true,  // 同时终止整个 run',
  '        };',
  '      }',
  '    }',
  '',
  '    // 2) 对特定工具做参数改写（如强制加上项目前缀）',
  '    if (tool.name === "list_directory" && (args as any)?.path == null) {',
  '      return { args: { ...(args as object), path: "/workspace/project" } };',
  '    }',
  '',
  '    // 3) 调用审计日志（不返回决策 = 继续执行）',
  '    console.log("[audit]", sessionKey, tool.name, args);',
  '  },',
  '',
  '  afterToolCall: async (ctx) => {',
  '    // ctx 额外带 result / isError',
  '    const { tool, result, isError } = ctx;',
  '',
  '    // 4) 错误上报 + 终止整个 run（例如连续 3 次失败）',
  '    if (isError) {',
  '      reportToSentry(tool.name, result.details?.error);',
  '      if (incrementFailures(ctx.sessionKey) >= 3) {',
  '        return { terminate: true };',
  '      }',
  '    }',
  '',
  '    // 5) 统一在 result.details 里注入 traceId（方便追踪）',
  '    return {',
  '      details: { traceId: crypto.randomUUID(), handledAt: Date.now() },',
  '    };',
  '  },',
  '});',
  '',
  'const runtime = createRuntime({',
  '  // ... model, streamFn, tools',
  '  extensions: [guard],',
  '});',
].join('\n');
