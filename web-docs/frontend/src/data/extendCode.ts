  '  createStreamFnFromAi,',
  '} from "@aipack-ai/agent";',
  '',
  '// ===== 方式 A：继承 BaseExtension =====',
  'class MetricsExtension extends BaseExtension {',
  '  readonly name = "metrics";',
  '',
  '  constructor() { super(); }',
  '',
  '  protected setup(hooks: RuntimeHooks, _ctx: ExtensionContext): void {',
  '    // 可用钩子：',
  '    //   beforeInitialize / afterInitialize',
  '    //   beforeRun (waterfall) / beforeTransform / afterTransform',
  '    //   beforeEmit / afterEmit / done / failed',
  '    //   beforeToolCall (waterfall) / afterToolCall (waterfall)',
  '',
  '    hooks.beforeInitialize.tapPromise("metrics", async (req) => {',
  '      // 记录开始时间（放到共享 Map 方便后续读取）',
  '      _ctx.shared.set("startAt", Date.now());',
  '      console.log("[metrics] 开始处理:", _ctx.sessionKey);',
  '    });',
  '',
  '    hooks.done.tapPromise("metrics", async (result) => {',
  '      const cost = Date.now() - (Number(_ctx.shared.get("startAt")) || 0);',
  '      console.log(`[metrics] 耗时 ${cost}ms  tokens=${result.usage.total}`);',
  '      // 可以把指标上报到 Prometheus / Sentry / 自研后台',
  '    });',
  '',
  '    hooks.failed.tapPromise("metrics", async (err, req) => {',
  '      console.error("[metrics] 运行失败:", err.message, _ctx.sessionKey);',
  '    });',
  '  }',
  '}',
  '',
  '// ===== 方式 B：对象字面量（更轻量） =====',
