  '// 内置 BM25 检索器，支持 CJK（中日韩 bigram）分词',
  '// 无需任何外部服务',
  '',
  '// ====== 升级：BM25 + 向量混合检索 ======',
  '// 只需提供 Embedder 接口，即可升级为双路独立召回：',
  '//   BM25 路 → top-limit*3 候选',
  '//   向量路 → top-limit*3 候选（独立于 BM25，不受其限制）',
  '//   两路各自 min-max 归一化后按权重融合',
  '',
  'const mem2 = createMemoryPlugin({',
  '  embedder: {',
  '    // 将文本转为向量（可接入 ollama / OpenAI / HuggingFace 等）',
