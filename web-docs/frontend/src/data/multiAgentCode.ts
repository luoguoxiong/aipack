export const maMapReduceCode = [
  'import { createMapReduce } from "@aipack-ai/multi-agent";',
  'import fs from "node:fs";',
  '',
  '// Mapper：处理单个子任务（如单个文件分析）',
  'const analyzer = {',
  '  id: "analyzer",',
  '  name: "代码分析师",',
  '  runtime: mk("你是代码分析师。分析给定代码文件的质量，输出：复杂度、问题列表、改进建议。"),',
  '};',
  '',
  '// Reducer：汇总所有 mapper 结果',
  'const summarizer = {',
  '  id: "summarizer",',
  '  name: "总结报告员",',
  '  runtime: mk("你是技术负责人。汇总多文件分析结果，生成项目级代码质量报告。"),',
  '};',
  '',
  '// createMapReduce：split → mapper 并行 → reducer 汇总',
  'const mapReduce = createMapReduce(analyzer, summarizer, {',
  '  // 必填：将输入拆分为多个子任务',
  '  split: (input) => input.split("\\n---\\n"),',
  '  // 可选：并行上限（避免 API 限流，默认 Infinity）',
  '  concurrency: 3,',
  '  // 可选：reducer 输入格式化（默认按 "--- 子任务 N ---" 拼接）',
  '  reduceInputFormat: (mapperResults) => {',
  '    const parts: string[] = [];',
  '    for (const [idx, result] of mapperResults) {',
  '      parts.push(`=== 文件 ${idx + 1} ===\\n${result.content}`);',
  '    }',
  '    return parts.join("\\n\\n");',
  '  },',
  '});',
  '',
  '// 多个文件内容用分隔符拼接后作为输入',
  'const files = [',
  '  fs.readFileSync("src/auth.ts", "utf-8"),',
  '  fs.readFileSync("src/api.ts", "utf-8"),',
  '  fs.readFileSync("src/db.ts", "utf-8"),',
  '  fs.readFileSync("src/utils.ts", "utf-8"),',
  '].join("\\n---\\n");',
  '',
  'const result = await mapReduce.run(files);',
  '// → 4 个 mapper 并行分析 → summarizer 汇总',
  'console.log(result.content); // 项目级代码质量报告',
].join('\n');

